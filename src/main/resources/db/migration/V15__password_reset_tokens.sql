-- V15: recuperar la contrasena. La persona pide un enlace con su correo y elige una contrasena nueva desde ahi.
-- Cada enlace sirve una vez y vence pronto (PasswordResetToken.VALIDITY). Igual que en las invitaciones, del enlace
-- se guarda solo su hash (SHA-256): con la base sola no se puede armar un enlace valido.

CREATE TABLE password_reset_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    token_hash varchar(64) NOT NULL UNIQUE,
    created_at timestamp(6) NOT NULL,
    expires_at timestamp(6) NOT NULL,
    used_at timestamp(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_password_reset_tokens_user FOREIGN KEY (user_id) REFERENCES users
);

CREATE INDEX idx_password_reset_tokens_user ON password_reset_tokens (user_id);
