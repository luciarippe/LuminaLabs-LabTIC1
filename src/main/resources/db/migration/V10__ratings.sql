-- V10: valoraciones de las actividades (RF-23, CU-08). Una por reserva: la restriccion UNIQUE de reservation_id
-- lo garantiza aunque el turista envie el formulario dos veces a la vez.
-- activity_id se guarda aunque se puede llegar por la reserva y el slot, para listar y promediar las
-- valoraciones de una actividad sin unir tres tablas (el slot de una reserva nunca cambia de actividad).

CREATE TABLE ratings (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    reservation_id bigint NOT NULL UNIQUE,
    activity_id bigint NOT NULL,
    stars integer NOT NULL CHECK (stars BETWEEN 1 AND 5),
    title varchar(100) NOT NULL,
    comment varchar(1000) NOT NULL,
    created_at timestamp(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_ratings_reservation FOREIGN KEY (reservation_id) REFERENCES reservations,
    CONSTRAINT fk_ratings_activity FOREIGN KEY (activity_id) REFERENCES activities
);

CREATE INDEX idx_ratings_activity ON ratings (activity_id, created_at);
