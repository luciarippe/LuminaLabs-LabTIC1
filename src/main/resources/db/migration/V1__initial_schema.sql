create table activities (
    booking_cutoff_minutes integer not null,
    cancellation_deadline_hours integer not null,
    cancellation_fee_percentage integer not null,
    duration_minutes integer not null,
    minimum_age integer,
    business_id bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    location_id bigint not null,
    name varchar(150) not null,
    accessibility varchar(1000),
    equipment varchar(1000),
    important_details varchar(2000),
    inclusions varchar(2000),
    description varchar(4000) not null,
    address varchar(255) not null,
    language varchar(255) not null,
    primary key (id)
);

create table activity_categories (
    id bigint generated by default as identity,
    description varchar(500),
    name varchar(255) not null unique,
    primary key (id)
);

create table activity_category_links (
    activity_id bigint not null,
    category_id bigint not null,
    primary key (activity_id, category_id)
);

create table business_locations (
    business_id bigint not null,
    location_id bigint not null,
    primary key (business_id, location_id)
);

create table business_providers (
    business_id bigint not null,
    provider_id bigint not null,
    primary key (business_id, provider_id)
);

create table businesses (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    reviewed_at timestamp(6),
    status_reason varchar(1000),
    description varchar(2000) not null,
    bank_account_number varchar(255) not null,
    bank_name varchar(255) not null,
    contact_email varchar(255) not null,
    contact_phone varchar(255) not null,
    identifier varchar(255) not null unique,
    legal_name varchar(255) not null,
    status varchar(255) not null check ((status in ('PENDING','APPROVED','DENIED','SUSPENDED'))),
    type varchar(255) not null check ((type in ('COMPANY','INDIVIDUAL'))),
    primary key (id)
);

create table locations (
    id bigint generated by default as identity,
    department varchar(255) not null check ((department in ('ARTIGAS','CANELONES','CERRO_LARGO','COLONIA','DURAZNO','FLORES','FLORIDA','LAVALLEJA','MALDONADO','MONTEVIDEO','PAYSANDU','RIO_NEGRO','RIVERA','ROCHA','SALTO','SAN_JOSE','SORIANO','TACUAREMBO','TREINTA_Y_TRES'))),
    name varchar(255) not null,
    primary key (id),
    unique (name, department)
);

create table slots (
    availability integer not null,
    max_capacity integer not null,
    price numeric(10,2) not null,
    activity_id bigint not null,
    id bigint generated by default as identity,
    start_time timestamp(6) not null,
    status varchar(255) not null check ((status in ('ACTIVE','CANCELLED'))),
    primary key (id),
    unique (activity_id, start_time)
);

create table users (
    birth_date date not null,
    id bigint generated by default as identity,
    user_type varchar(31) not null check ((user_type in ('ADMIN','PROVIDER','TOURIST'))),
    email varchar(255) not null unique,
    first_name varchar(255) not null,
    last_name varchar(255) not null,
    password_hash varchar(255) not null,
    username varchar(255) not null unique,
    primary key (id)
);

