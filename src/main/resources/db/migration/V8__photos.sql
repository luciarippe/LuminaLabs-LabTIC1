-- Fotos de actividades y de localidades. Las imagenes se guardan en la base (ya achicadas y en JPG, ver
-- ImageProcessor) para no depender de carpetas del servidor. Cada foto subida es una fila nueva de images:
-- nunca se modifica, asi su direccion (/photos/{id}) se puede guardar en cache sin vencimiento.
CREATE TABLE images (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    content_type varchar(50) NOT NULL,
    data bytea NOT NULL,
    width integer NOT NULL,
    height integer NOT NULL,
    created_at timestamp(6) NOT NULL,
    PRIMARY KEY (id)
);

-- Fotos de una actividad, en orden: la de posicion 0 es la portada
CREATE TABLE activity_photos (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    activity_id bigint NOT NULL,
    image_id bigint NOT NULL UNIQUE,
    position integer NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_activity_photos_activity FOREIGN KEY (activity_id) REFERENCES activities,
    CONSTRAINT fk_activity_photos_image FOREIGN KEY (image_id) REFERENCES images
);
CREATE INDEX idx_activity_photos_activity ON activity_photos (activity_id, position);

-- Foto de cada localidad (la carga el administrador)
ALTER TABLE locations ADD COLUMN photo_id bigint UNIQUE;
ALTER TABLE locations ADD CONSTRAINT fk_locations_photo FOREIGN KEY (photo_id) REFERENCES images;
