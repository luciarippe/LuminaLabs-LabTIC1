-- V4: cancelaciones y devoluciones (RF-19, CU-05) y aviso de cambio de horario (CU-05 4b)

-- Las devoluciones usan un estado nuevo, PENDING. Al agregar un valor a un enum hay que actualizar
-- tambien el CHECK de la columna, si no la base rechaza el valor nuevo. Postgres le puso a este CHECK
-- el nombre "payments_status_check" al crear la tabla en V3.
ALTER TABLE payments DROP CONSTRAINT payments_status_check;
ALTER TABLE payments ADD CONSTRAINT payments_status_check
    CHECK (status IN ('NO_RESPONSE','APPROVED','REJECTED','PENDING'));

-- El proceso automatico busca las devoluciones pendientes para reintentarlas
CREATE INDEX idx_payments_type_status ON payments (type, status);

ALTER TABLE reservations ADD COLUMN schedule_changed boolean NOT NULL DEFAULT false;

CREATE TABLE cancellations (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    reservation_id bigint NOT NULL UNIQUE,
    reason varchar(255) NOT NULL CHECK (reason IN ('TOURIST','SLOT_CANCELLED','BUSINESS_SUSPENDED')),
    cancelled_at timestamp(6) NOT NULL,
    fee_amount numeric(12,2) NOT NULL,
    refund_amount numeric(12,2) NOT NULL,
    refund_payment_id bigint UNIQUE,
    PRIMARY KEY (id),
    CONSTRAINT fk_cancellations_reservation FOREIGN KEY (reservation_id) REFERENCES reservations,
    CONSTRAINT fk_cancellations_refund_payment FOREIGN KEY (refund_payment_id) REFERENCES payments
);
