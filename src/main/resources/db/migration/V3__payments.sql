-- V3: intentos de pago de las reservas (RF-17, RF-18). Ver la entidad Payment.

CREATE TABLE payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    reservation_id bigint NOT NULL,
    type varchar(255) NOT NULL CHECK (type IN ('CHARGE','REFUND')),
    amount numeric(12,2) NOT NULL,
    status varchar(255) NOT NULL CHECK (status IN ('NO_RESPONSE','APPROVED','REJECTED')),
    external_id varchar(255),
    -- De la tarjeta solo se guardan el titular y los ultimos 4 digitos
    card_holder varchar(255) NOT NULL,
    card_last_digits varchar(4) NOT NULL,
    created_at timestamp(6) NOT NULL,
    resolved_at timestamp(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_payments_reservation FOREIGN KEY (reservation_id) REFERENCES reservations
);

-- Los pagos siempre se buscan por reserva
CREATE INDEX idx_payments_reservation ON payments (reservation_id);
