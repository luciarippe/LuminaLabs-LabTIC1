-- V11: invitaciones para sumar prestadores a un emprendimiento (CU-15 4a). Cuando el correo no tiene cuenta, se le
-- manda un enlace para crearla; la cuenta se crea recien cuando la persona completa sus datos y su contrasena.
-- Del enlace se guarda solo su hash (SHA-256): con la base sola no se puede armar un enlace valido.

CREATE TABLE provider_invitations (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    business_id bigint NOT NULL,
    email varchar(254) NOT NULL,
    token_hash varchar(64) NOT NULL UNIQUE,
    invited_by_id bigint NOT NULL,
    created_at timestamp(6) NOT NULL,
    expires_at timestamp(6) NOT NULL,
    accepted_at timestamp(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_provider_invitations_business FOREIGN KEY (business_id) REFERENCES businesses,
    CONSTRAINT fk_provider_invitations_invited_by FOREIGN KEY (invited_by_id) REFERENCES users
);

CREATE INDEX idx_provider_invitations_business ON provider_invitations (business_id);
