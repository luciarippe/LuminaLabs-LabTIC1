-- V2: cambios del 17/10/2026
--   1. slots.version: bloqueo optimista (@Version en Slot, RNF-12).
--   2. slots.active_start_time: la restriccion unica pasa a ser (activity_id, active_start_time), asi un slot
--      cancelado (active_start_time NULL) no impide crear otro a la misma hora (ver Slot.activeStartTime).
--   3. Tablas reservations y reservation_participants (RF-16). La reserva guarda el precio del momento.
--
-- Es idempotente (IF NOT EXISTS / IF EXISTS) a proposito: algunas bases ya tenian parte de estos cambios
-- porque se hicieron con ddl-auto=update antes de configurar Flyway. Las migraciones siguientes no necesitan serlo.

-- 1. Bloqueo optimista. "default 0" completa las filas que ya existian.
ALTER TABLE slots ADD COLUMN IF NOT EXISTS version bigint DEFAULT 0 NOT NULL;

-- 2. Restriccion unica solo entre slots activos
ALTER TABLE slots ADD COLUMN IF NOT EXISTS active_start_time timestamp(6);
UPDATE slots SET active_start_time = start_time WHERE status = 'ACTIVE' AND active_start_time IS NULL;

-- La restriccion vieja tiene un nombre distinto segun como se creo cada base
-- (ej. "uk3wt9cxbleg7nmvpyef1ux6gqm" o "slots_activity_id_start_time_key"), por eso se busca por definicion.
DO $$
DECLARE old_constraint text;
BEGIN
    FOR old_constraint IN
        SELECT conname FROM pg_constraint
        WHERE conrelid = 'slots'::regclass AND contype = 'u'
          AND pg_get_constraintdef(oid) = 'UNIQUE (activity_id, start_time)'
    LOOP
        EXECUTE format('ALTER TABLE slots DROP CONSTRAINT %I', old_constraint);
    END LOOP;
END $$;

ALTER TABLE slots DROP CONSTRAINT IF EXISTS uk_slots_activity_active_start;
ALTER TABLE slots ADD CONSTRAINT uk_slots_activity_active_start UNIQUE (activity_id, active_start_time);

-- 3. Reservas y participantes
CREATE TABLE IF NOT EXISTS reservations (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tourist_id bigint NOT NULL,
    slot_id bigint NOT NULL,
    participant_count integer NOT NULL,
    unit_price numeric(10,2) NOT NULL,
    total_amount numeric(12,2) NOT NULL,
    status varchar(255) NOT NULL CHECK (status IN ('PENDING_PAYMENT','CONFIRMED','CANCELLED','EXPIRED','FINISHED')),
    created_at timestamp(6) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS reservation_participants (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    reservation_id bigint NOT NULL,
    first_name varchar(255) NOT NULL,
    last_name varchar(255) NOT NULL,
    birth_date date NOT NULL,
    PRIMARY KEY (id)
);

